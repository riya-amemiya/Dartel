fn checksum(bytes: &[u8]) -> u32 {
    !bytes.iter().fold(u32::MAX, |sum, &byte| {
        (0..8).fold(sum ^ u32::from(byte), |sum, _| {
            if sum & 1 == 1 {
                0xEDB8_8320 ^ (sum >> 1)
            } else {
                sum >> 1
            }
        })
    })
}

fn file(chunks: &[(&[u8; 4], &[u8])]) -> Vec<u8> {
    chunks
        .iter()
        .fold(SIGNATURE.to_vec(), |mut file, (kind, data)| {
            let body = [&kind[..], data].concat();
            file.extend_from_slice(&(data.len() as u32).to_be_bytes());
            file.extend_from_slice(&body);
            file.extend_from_slice(&checksum(&body).to_be_bytes());
            file
        })
}

fn header(width: u32, height: u32, depth: u8, color: u8, tail: [u8; 3]) -> Vec<u8> {
    [
        &width.to_be_bytes()[..],
        &height.to_be_bytes(),
        &[depth, color],
        &tail,
    ]
    .concat()
}

fn stored(data: &[u8]) -> Vec<u8> {
    let (low, high) = data.iter().fold((1_u32, 0_u32), |(low, high), &byte| {
        (
            (low + u32::from(byte)) % 65521,
            (high + low + u32::from(byte)) % 65521,
        )
    });
    [
        &[0x78, 0x01, 0x01][..],
        &(data.len() as u16).to_le_bytes(),
        &(!(data.len() as u16)).to_le_bytes(),
        data,
        &(high << 16 | low).to_be_bytes(),
    ]
    .concat()
}

fn picture(header: &[u8], scanlines: &[u8]) -> Vec<u8> {
    file(&[
        (b"IHDR", header),
        (b"IDAT", &stored(scanlines)),
        (b"IEND", &[]),
    ])
}

fn filtered(kind: u8, line: [u8; 3]) -> Option<Vec<u8>> {
    decode(&picture(
        &header(3, 2, 8, 0, [0; 3]),
        &[0, 10, 20, 30, kind, line[0], line[1], line[2]],
    ))
    .map(|image| image.pixels)
}

fn rejected(header: &[u8]) -> bool {
    decode(&file(&[
        (b"IHDR", header),
        (b"IDAT", &stored(&[0, 0])),
        (b"IEND", &[]),
    ]))
    .is_none()
}

fn gray(values: &[u8]) -> Vec<u8> {
    values
        .iter()
        .flat_map(|&value| [value, value, value, 255])
        .collect()
}

fn grid() -> Vec<u8> {
    (0..5_u8)
        .flat_map(|y| (0..5).flat_map(move |x| [x * 50, y * 50, (x + y) * 25, 255]))
        .collect()
}

#[test]
fn image_compressed_with_fixed_codes_is_decoded() {
    let image = decode(GRID).map(|image| (image.width, image.height, image.pixels));
    assert_eq!(image, Some((5, 5, grid())));
}

